/**
 * Embeds ui/app.html and the fonts into ui.gen.ts, so the program is one file
 * with no internet needed at runtime.
 *   node build-ui.ts
 * Fonts are read from ./fonts if present (committed to the repo), else from the
 * system font folders the build machine has.
 */
import fs from 'node:fs';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname);
const html = fs.readFileSync(path.join(here, 'ui', 'app.html'), 'utf8');

const want: [string, string, string[]][] = [
  ['inter-400', 'font/otf', ['fonts/Inter-Regular.otf', '/usr/share/fonts/opentype/inter/Inter-Regular.otf']],
  ['inter-500', 'font/otf', ['fonts/Inter-Medium.otf', '/usr/share/fonts/opentype/inter/Inter-Medium.otf']],
  ['inter-600', 'font/otf', ['fonts/Inter-SemiBold.otf', '/usr/share/fonts/opentype/inter/Inter-SemiBold.otf']],
  ['inter-display-600', 'font/otf', ['fonts/InterDisplay-SemiBold.otf', '/usr/share/fonts/opentype/inter/InterDisplay-SemiBold.otf']],
  ['lora-italic', 'font/ttf', ['fonts/Lora-Italic-Variable.ttf', '/usr/share/fonts/truetype/google-fonts/Lora-Italic-Variable.ttf']],
];

const fonts: Record<string, { mime: string; b64: string }> = {};
for (const [name, mime, paths] of want) {
  const p = paths.map(x => (path.isAbsolute(x) ? x : path.join(here, x))).find(x => fs.existsSync(x));
  if (!p) { console.warn(`font ${name} not found; the page falls back to system fonts`); continue; }
  fonts[name] = { mime, b64: fs.readFileSync(p).toString('base64') };
}

const out = `// GENERATED by build-ui.ts from ui/app.html and fonts/. Do not edit.\n` +
  `export const APP_HTML: string = ${JSON.stringify(html)};\n` +
  `export const FONTS: Record<string, { mime: string; b64: string }> = ${JSON.stringify(fonts)};\n`;
fs.writeFileSync(path.join(here, 'ui.gen.ts'), out);
console.log(`ui.gen.ts: page ${(html.length / 1024).toFixed(0)} KB, ${Object.keys(fonts).length} fonts`);
